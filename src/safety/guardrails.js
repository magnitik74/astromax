/**
 * Проверка текста сообщения на наличие красных линий
 * @param {string} text - Входящее сообщение пользователя
 * @returns {{ safe: boolean, category: string|null, response: string|null }}
 */
export function checkSafetyGuardrails(text) {
  if (!text || typeof text !== 'string') {
    return { safe: true, category: null, response: null };
  }

  const cleanText = text.trim();

  for (const [category, patterns] of Object.entries(PATTERNS)) {
    for (const pattern of patterns) {
      if (pattern.test(cleanText)) {
        return {
          safe: false,
          category,
          response: SOFT_PIVOT_RESPONSES[category],
        };
      }
    }
  }

  return { safe: true, category: null, response: null };
}
