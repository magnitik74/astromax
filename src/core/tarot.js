/**
 * Генерация полной канонической колоды (78 карт) с изображениями и оракулом
 */
export function getFullDeck() {
  const deck = [...MAJOR_ARCANA];

  let idCounter = 100;
  for (const suit of SUITS) {
    for (let i = 0; i < COURT_NAMES.length; i++) {
      const cardName = `${COURT_NAMES[i]} ${suit.name}`;
      const prefix = COURT_FILE_PREFIXES[i];
      const imgPath = `/images/tarot/${prefix}of${suit.id}.jpeg`;

      let oracleUpright = 'Да';
      let oracleReversed = 'Скорее нет';

      if (suit.id === 'wands') {
        if ([0, 2, 3, 5, 7, 12, 13].includes(i)) {
          oracleUpright = 'Да (активное действие)';
        } else {
          oracleUpright = 'Зависит от упорства';
          oracleReversed = 'Нет (сопротивление среды)';
        }
      } else if (suit.id === 'cups') {
        if ([0, 1, 2, 8, 9, 12, 13].includes(i)) {
          oracleUpright = 'Искреннее Да (гармония)';
        } else {
          oracleUpright = 'Пока нет (эмоциональный блок)';
          oracleReversed = 'Скорее да (выход на свет)';
        }
      } else if (suit.id === 'pentacles') {
        if ([0, 2, 5, 7, 8, 9, 12, 13].includes(i)) {
          oracleUpright = 'Твердое Да (рост достатка)';
        } else {
          oracleUpright = 'Зависит от расчёта';
          oracleReversed = 'Нет (финансовый риск)';
        }
      } else if (suit.id === 'swords') {
        if ([0, 5].includes(i)) {
          oracleUpright = 'Да (ясность ума и победа)';
        } else if ([1, 3].includes(i)) {
          oracleUpright = 'Пока нет (нужна пауза)';
        } else {
          oracleUpright = 'Нет (осторожно, барьеры)';
          oracleReversed = 'Выход из кризиса';
        }
      }

      deck.push({
        id: idCounter++,
        name: cardName,
        arcana: 'minor',
        suit: suit.id,
        suitName: suit.name,
        element: suit.element,
        keywords: [suit.name, COURT_NAMES[i]],
        upright: `Энергия масти ${suit.name} (${suit.meaning}) раскрывается в созидательном ключе. Карта ${cardName} открывает путь к реализации задуманного.`,
        reversed: `Блок или переизбыток в сфере ${suit.meaning}. Карта ${cardName} предупреждает о необходимости калибровки и осторожности.`,
        image: imgPath,
        love: `В отношениях энергия ${suit.name}: важно слышать импульс сердца и сохранять взаимность.`,
        finance: `В делах и деньгах: стабильное движение, опирайся на трезвый расчет и мастерство.`,
        advice: `Используй силу масти ${suit.name}: ${suit.meaning.toLowerCase()}.`,
        oracleUpright,
        oracleReversed,
      });
    }
  }
  return deck;
}

/**
 * Детерминированный генератор псевдослучайных чисел на основе сида
 */
function getSeededRandom(seedString) {
  let h = 0x811c9dc5;
  for (let i = 0; i < seedString.length; i++) {
    h ^= seedString.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return function() {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
}

/**
 * Расклад Таро с поддержкой криптографической случайности и детерминированного сида
 * @param {Object} options
 * @param {string} options.type - 'daily' (1 карта), 'oracle_yes_no' (1 карта), 'three_cards' (3 карты), 'love' (5 карт), 'celtic_cross' (10 карт)
 * @param {boolean} [options.allowReversed=true] - учитывать ли перевернутые карты
 * @param {string} [options.seed] - детерминированный сид (например, userId + YYYY-MM-DD)
 * @param {string|number} [options.userId] - ID пользователя для автогенерации сида суточной карты
 */
export function drawTarotSpread({ type = 'daily', allowReversed = true, seed = null, userId = null } = {}) {
  const deck = getFullDeck();

  let effectiveSeed = seed;
  if (!effectiveSeed && type === 'daily' && userId) {
    const today = new Date().toISOString().slice(0, 10);
    effectiveSeed = `${userId}_${today}`;
  }

  // Перемешивание колоды: либо детерминированное по сиду, либо криптографическое
  if (effectiveSeed) {
    const prng = getSeededRandom(String(effectiveSeed));
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(prng() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  } else {
    for (let i = deck.length - 1; i > 0; i--) {
      const j = crypto.randomInt(0, i + 1);
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  }

  let count = 1;
  let positions = ['Карта Дня (Твой космический фокус)'];

  if (type === 'oracle_yes_no') {
    count = 1;
    positions = ['Оракул Да / Нет (Ответ Аркана)'];
  } else if (type === 'three_cards') {
    count = 3;
    positions = ['Прошлое (Фундамент ситуации)', 'Настоящее (Точка силы)', 'Будущее (Куда ведет энергия)'];
  } else if (type === 'love') {
    count = 5;
    positions = [
      'Твое состояние',
      'Его / Ее истинные мысли',
      'Тайная динамика между вами',
      'Главный барьер или страх',
      'К какому союзу вы движетесь',
    ];
  } else if (type === 'celtic_cross') {
    count = 10;
    positions = [
      'Суть вопроса (Сердце ситуации)',
      'Встречный фактор (Что помогает или мешает)',
      'Фундамент (Глубинная основа)',
      'Недавнее прошлое (Что уходит)',
      'Высшая цель (Возможный максимум)',
      'Ближайшее будущее (Что на пороге)',
      'Твоя позиция (Внутренняя сила)',
      'Окружение (Внешние факторы)',
      'Надежды и скрытые страхи',
      'Итоговый исход (Вектор судьбы)',
    ];
  }

  const drawn = deck.slice(0, count).map((card, idx) => {
    let isReversed = false;
    if (allowReversed) {
      if (effectiveSeed) {
        const prng = getSeededRandom(`${effectiveSeed}_card_${idx}`);
        isReversed = prng() < 0.28;
      } else {
        isReversed = crypto.randomInt(0, 100) < 28;
      }
    }

    return {
      position: positions[idx] || `Позиция ${idx + 1}`,
      card: {
        id: card.id,
        name: card.name,
        arcana: card.arcana,
        suit: card.suit || null,
        element: card.element || (card.arcana === 'major' ? 'Дух' : ''),
        keywords: card.keywords,
        image: card.image,
        isReversed,
        status: isReversed ? 'Перевернутая' : 'Прямая',
        interpretation: isReversed ? card.reversed : card.upright,
        love: card.love || '',
        finance: card.finance || '',
        advice: card.advice || '',
        oracleVerdict: isReversed ? card.oracleReversed : card.oracleUpright,
      },
    };
  });

  return {
    spreadType: type,
    isDeterministic: Boolean(effectiveSeed),
    timestamp: new Date().toISOString(),
    cards: drawn,
  };
}
