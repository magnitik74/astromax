/**
 * Генерация полной колоды (78 карт)
 */
export function getFullDeck() {
  const deck = [...MAJOR_ARCANA];
  const courtNames = ['Туз', 'Двойка', 'Тройка', 'Четверка', 'Пятерка', 'Шестерка', 'Семерка', 'Восьмерка', 'Девятка', 'Десятка', 'Паж', 'Рыцарь', 'Королева', 'Король'];

  let idCounter = 100;
  for (const suit of SUITS) {
    for (let i = 0; i < courtNames.length; i++) {
      const cardName = `${courtNames[i]} ${suit.name}`;
      deck.push({
        id: idCounter++,
        name: cardName,
        arcana: 'minor',
        suit: suit.id,
        suitName: suit.name,
        element: suit.element,
        keywords: [suit.name, courtNames[i]],
        upright: `Энергия масти ${suit.name} (${suit.meaning}) раскрывается в созидательном ключе.`,
        reversed: `Блок или переизбыток в сфере ${suit.meaning}. Необходима калибровка.`,
      });
    }
  }
  return deck;
}

/**
 * Расклад Таро с криптографической случайностью
 * @param {Object} options
 * @param {string} options.type - 'daily' (1 карта), 'three_cards' (3 карты: Прошлое, Настоящее, Будущее), 'love' (5 карт)
 * @param {boolean} [options.allowReversed=true] - учитывать ли перевернутые карты
 */
export function drawTarotSpread({ type = 'daily', allowReversed = true } = {}) {
  const deck = getFullDeck();
  
  // Перемешивание по алгоритму Фишера-Йетса с криптографической случайностью
  for (let i = deck.length - 1; i > 0; i--) {
    const j = crypto.randomInt(0, i + 1);
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }

  let count = 1;
  let positions = ['Карта Дня (Твой космический фокус)'];

  if (type === 'three_cards') {
    count = 3;
    positions = ['Прошлое (Фундамент ситуации)', 'Настоящее (Точка силы)', 'Будущее (Куда ведет энергия)'];
  } else if (type === 'love') {
    count = 5;
    positions = [
      'Твое состояние',
      'Его / Ее истинные мысли',
      'Тайная динамика между вами',
      'Главный барьер или страх',
      'К какому союзу вы движетесь',
    ];
  }

  const drawn = deck.slice(0, count).map((card, idx) => {
    const isReversed = allowReversed ? crypto.randomInt(0, 100) < 30 : false; // 30% шанс перевернутой
    return {
      position: positions[idx] || `Позиция ${idx + 1}`,
      card: {
        id: card.id,
        name: card.name,
        arcana: card.arcana,
        element: card.element || (card.arcana === 'major' ? 'Дух' : ''),
        keywords: card.keywords,
        isReversed,
        status: isReversed ? 'Перевернутая' : 'Прямая',
        interpretation: isReversed ? card.reversed : card.upright,
      },
    };
  });

  return {
    spreadType: type,
    timestamp: new Date().toISOString(),
    cards: drawn,
  };
}
